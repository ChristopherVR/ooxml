// Bundles the core's server-side update validator (src/core/teams/validate-update.ts) and the
// protocol constants into viewers/teams/server/validator.generated.mjs, so the standalone
// `openteams-server` package can enforce authorship without depending on ooxml-core. `yjs`, `lib0`
// and `y-protocols` stay external (the server already depends on them). Run
// `node scripts/bundle-validator.mjs` after changing either source; `--check` fails when the
// committed file is stale (the script test runs it).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const core = path.resolve(here, '../../../src/core/teams');
export const OUTPUT = path.resolve(here, '../server/validator.generated.mjs');

const ENTRY = `export { validateTeamsSyncMessage, validateTeamsUpdate } from './validate-update';
export { PROTOCOL_VERSION, PROTOCOL_PARAM, protocolOfUrl } from './protocol';
`;

const HEADER = `// GENERATED by scripts/bundle-validator.mjs from src/core/teams/validate-update.ts and
// protocol.ts (ooxml-core). Do not edit; run \`node scripts/bundle-validator.mjs\` instead.
`;

/** The bundle text for the current sources. */
export async function bundleValidator() {
	const result = await build({
		stdin: { contents: ENTRY, resolveDir: core, sourcefile: 'validator-entry.ts', loader: 'ts' },
		bundle: true,
		format: 'esm',
		platform: 'node',
		target: 'node22',
		external: ['yjs', 'lib0/*', 'y-protocols/*'],
		write: false,
		legalComments: 'none',
		treeShaking: true,
		charset: 'utf8',
		logLevel: 'silent',
	});
	return HEADER + result.outputFiles[0].text.replace(/\r\n/gu, '\n');
}

/** True when the committed bundle matches the current sources. */
export async function isBundleCurrent() {
	let current = '';
	try {
		current = readFileSync(OUTPUT, 'utf8').replace(/\r\n/gu, '\n');
	} catch {}
	return current === (await bundleValidator());
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	if (process.argv.includes('--check')) {
		if (!(await isBundleCurrent())) {
			console.error(
				'server/validator.generated.mjs is stale: run node scripts/bundle-validator.mjs',
			);
			process.exit(1);
		}
	} else {
		const next = await bundleValidator();
		writeFileSync(OUTPUT, next);
		console.log(`wrote ${path.relative(process.cwd(), OUTPUT)} (${next.length} bytes)`);
	}
}
