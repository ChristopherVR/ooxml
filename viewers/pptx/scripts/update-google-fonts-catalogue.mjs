#!/usr/bin/env node
/**
 * Regenerate `src/core/text/webfonts/google-fonts-catalogue.ts` from the
 * Google Fonts metadata feed. Bundled metadata avoids per-family probes.
 *
 * Run: `bun run fonts:catalogue` (or `node scripts/update-google-fonts-catalogue.mjs`).
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const METADATA_URL = 'https://fonts.google.com/metadata/fonts';
const OUT_PATH = resolve(
	dirname(fileURLToPath(import.meta.url)),
	'../../../src/core/text/webfonts/google-fonts-catalogue.ts',
);

/** Standard weights occupy bits 0..8 (normal) and 9..17 (italic). */
export function familyVariantMask(entry) {
	if (!entry.fonts || typeof entry.fonts !== 'object') {
		throw new Error(`missing font faces for ${entry.family}`);
	}
	const styles = new Set();
	let mask = 0;
	for (const key of Object.keys(entry.fonts)) {
		const match = /^(\d+(?:\.\d+)?)(i?)$/u.exec(key);
		if (!match) {
			throw new Error(`unrecognised face ${key} for ${entry.family}`);
		}
		const weight = Number(match[1]);
		const offset = match[2] ? 9 : 0;
		styles.add(offset);
		if (weight >= 100 && weight <= 900 && weight % 100 === 0) {
			mask |= 1 << (weight / 100 - 1 + offset);
		}
	}
	const axis = entry.axes?.find((candidate) => candidate.tag === 'wght');
	if (axis) {
		if (!Number.isFinite(axis.min) || !Number.isFinite(axis.max) || axis.min > axis.max) {
			throw new Error(`invalid weight axis for ${entry.family}`);
		}
		// A weight axis does not imply italic support: expand only styles in the feed.
		for (const offset of styles) {
			for (let weight = 100; weight <= 900; weight += 100) {
				if (weight >= axis.min && weight <= axis.max) {
					mask |= 1 << (weight / 100 - 1 + offset);
				}
			}
		}
	}
	return mask;
}

/** Pure generation entry point for fixture tests and reproducible offline refreshes. */
export function generateCatalogue(metadata, date, minimumFamilies = 1000) {
	const entries = new Map();
	for (const entry of metadata.familyMetadataList) {
		if (typeof entry.family !== 'string' || !entry.family.trim()) {
			continue;
		}
		const family = entry.family.trim();
		entries.set(family, (entries.get(family) ?? 0) | familyVariantMask(entry));
	}
	const families = [...entries.keys()].sort((a, b) => a.localeCompare(b, 'en'));
	if (families.length < minimumFamilies) {
		throw new Error(
			`only ${families.length} families in the feed; refusing to shrink the catalogue`,
		);
	}
	// Single quotes match oxfmt. Four base-36 digits hold all eighteen face bits.
	const quote = (value) => `'${value.replace(/[\\']/gu, '\\$&')}'`;
	const body = families.map((family) => `\t${quote(family)},`).join('\n');
	const masks = families
		.map((family) => entries.get(family).toString(36).padStart(4, '0'))
		.join('');
	const chunks = masks.match(/.{1,88}/gu) ?? [''];
	const packed = chunks.map((chunk) => `\t${quote(chunk)}`).join(' +\n');
	return `/**
 * GENERATED by scripts/update-google-fonts-catalogue.mjs on ${date}; do not
 * edit by hand. Family names and supported standard-weight faces from
 * ${METADATA_URL}, in the API's own spelling.
 *
 * Refresh with \`bun run fonts:catalogue\` when Google adds or updates fonts.
 */

/** Date the catalogue was last regenerated (ISO yyyy-mm-dd). */
export const GOOGLE_FONTS_CATALOGUE_DATE = '${date}';

/** Family names served by the Google Fonts CSS2 API, sorted. */
export const GOOGLE_FONTS_FAMILIES: readonly string[] = [
${body}
];

/**
 * @internal Four base-36 digits per family, in GOOGLE_FONTS_FAMILIES order.
 * Bits 0..8 represent weights 100..900; bits 9..17 represent their italics.
 */
export const GOOGLE_FONTS_VARIANT_MASKS =
${packed};
`;
}

async function main() {
	const response = await fetch(METADATA_URL);
	if (!response.ok) {
		throw new Error(`${METADATA_URL} answered ${response.status}`);
	}
	// The feed has historically carried an anti-JSON-hijacking `)]}'` prefix.
	const text = (await response.text()).replace(/^\)\]\}'\s*/u, '');
	const metadata = JSON.parse(text);
	const source = generateCatalogue(metadata, new Date().toISOString().slice(0, 10));
	writeFileSync(OUT_PATH, source);
	console.log(
		`Wrote ${metadata.familyMetadataList.length} families and their faces to ${OUT_PATH}`,
	);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await main();
}
