import type { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import type { PptxElement } from 'pptx-viewer-core';

import { getSilhouetteFilterDef } from './element-effect-defs';

/** Injectable silhouette shadow / glow `<filter>` descriptor: id + sanitized markup. */
export interface SilhouetteFilterDef {
	id: string;
	markup: SafeHtml;
}

/**
 * The silhouette shadow / glow `<filter>` of a shape (shared
 * `getSilhouetteEffects`) with its markup sanitized for `[innerHTML]`, or
 * `undefined` when the shape paints them as a plain box-shadow. Like the bevel
 * lighting filter, the markup is a complete `<filter>` element generated by
 * shared code, injected verbatim.
 */
export function resolveSilhouetteFilter(
	element: PptxElement,
	sanitizer: DomSanitizer,
): SilhouetteFilterDef | undefined {
	const def = getSilhouetteFilterDef(element);
	return def
		? { id: def.id, markup: sanitizer.bypassSecurityTrustHtml(def.filterMarkup) }
		: undefined;
}
