Remove-Item $Out -ErrorAction SilentlyContinue
$v = New-Object -ComObject Visio.Application
$v.Visible = $false
$v.AlertResponse = 1
try {
	$d = $v.Documents.Add('')
	$s = $d.Pages.Item(1).DrawRectangle(1, 1, 3, 2)
	$i = 0
	foreach ($f in (Get-Content $Cases)) {
		$i++
		try {
			$null = $s.AddNamedRow(242, "r$i", 0)
			$c = $s.CellsU("User.r$i")
			$c.FormulaForceU = $f
			$line = '{0} => {1} | str={2}' -f $f, $c.Result(0), $c.ResultStr(0)
		} catch { $line = '{0} => ERR {1}' -f $f, $_.Exception.Message }
		Add-Content $Out $line
	}
	$d.Saved = $true
	$d.Close()
} finally { $v.Quit() }
Get-Content $Out
