import type { ThemeColorTuple, ThemePreset } from './theme-presets';

type Colors = readonly [string, string, string, string, string, string];

function legacy(label: string, majorFont: string, minorFont: string, accents: Colors): ThemePreset {
	const [first, , , , , last] = accents;
	return measured(label, majorFont, minorFont, [
		'FFFFFF',
		'000000',
		'F2F2F2',
		'303030',
		...accents,
		first,
		last,
	]);
}

function measured(
	label: string,
	majorFont: string,
	minorFont: string,
	colors: ThemeColorTuple,
): ThemePreset {
	return { id: label.toLowerCase().replaceAll(' ', '-'), label, colors, majorFont, minorFont };
}

