#!/usr/bin/env node
/**
 * Regenerate `pptx/core/utils/smartart-builtin-layouts/{catalog,data}.ts`: PowerPoint's built-in
 * SmartArt layout definitions (`dgm:layoutDef`), one per `uniqueId`, taken from the layout parts
 * of the ground-truth gallery fixtures (`__tests__/fixtures/smartart-gallery`, which PowerPoint
 * itself produced via COM; see its README).
 *
 * `data.ts` holds the definitions as one base64 blob of per-layout gzip members, so a swap
 * inflates only the layout it needs; `catalog.ts` is the small index (id, title, category and the
 * byte range of the member). Output is deterministic for the same fixtures.
 *
 * Usage: `node scripts/pptx/gen-smartart-builtin-layouts.mjs` from `src/core`.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

import JSZip from 'jszip';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const GALLERY = path.resolve(HERE, '../../pptx/__tests__/fixtures/smartart-gallery');
const OUT = path.resolve(HERE, '../../pptx/core/utils/smartart-builtin-layouts');

const manifest = JSON.parse(readFileSync(path.join(GALLERY, 'manifest.json'), 'utf8'));
const titles = new Map(manifest.map((entry) => [entry.file, entry]));

const layouts = new Map();
for (const file of readdirSync(GALLERY)
	.filter((name) => name.endsWith('.pptx'))
	.sort()) {
	const zip = await JSZip.loadAsync(readFileSync(path.join(GALLERY, file)));
	for (const name of Object.keys(zip.files).sort()) {
		if (!/^ppt\/diagrams\/layout\d*\.xml$/u.test(name)) continue;
		const xml = (await zip.file(name).async('string')).replace(/>\s+</gu, '><');
		const id = /<[\w:]*layoutDef\b[^>]*\buniqueId="([^"]+)"/u.exec(xml)?.[1];
		if (!id || layouts.has(id)) continue;
		const cat = /<[\w:]*cat\b[^>]*\btype="([^"]+)"/u.exec(xml)?.[1] ?? 'list';
		layouts.set(id, { id, xml, title: titles.get(file)?.layoutName ?? id, category: cat });
	}
}

const members = [];
const catalog = [];
let offset = 0;
for (const layout of [...layouts.values()].sort((a, b) => a.id.localeCompare(b.id))) {
	const packed = gzipSync(Buffer.from(layout.xml, 'utf8'), { level: 9, mtime: 0 });
	members.push(packed);
	catalog.push({
		id: layout.id,
		title: layout.title,
		category: layout.category,
		offset,
		length: packed.length,
	});
	offset += packed.length;
}

const header = '// Generated by scripts/pptx/gen-smartart-builtin-layouts.mjs. Do not edit.\n';
writeFileSync(
	path.join(OUT, 'catalog.ts'),
	`${header}import type { BuiltinSmartArtLayoutEntry } from './types';\n\n` +
		`export const BUILTIN_SMARTART_LAYOUTS: readonly BuiltinSmartArtLayoutEntry[] = ${JSON.stringify(catalog, null, '\t')};\n`,
);
writeFileSync(
	path.join(OUT, 'data.ts'),
	`${header}/** Per-layout gzip members, concatenated and base64 encoded (ranges in catalog.ts). */\n` +
		`export const BUILTIN_SMARTART_LAYOUT_DATA = '${Buffer.concat(members).toString('base64')}';\n`,
);
console.log(`${catalog.length} layouts, ${offset} gzip bytes`);
