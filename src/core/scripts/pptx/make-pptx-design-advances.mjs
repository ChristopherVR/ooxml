// Writes src/core/text/font-metrics/design-advances-powerpoint.generated.ts from the JSON that
// record-pptx-design-advances.ps1 prints:
//
//   pwsh -File src/core/scripts/pptx/record-pptx-design-advances.ps1 -Fonts 'Aptos','Consolas' > advances.json
//   node src/core/scripts/pptx/make-pptx-design-advances.mjs advances.json
//
// Pass every font the table should hold: the file is rewritten from the JSON alone.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
	console.error('usage: node make-pptx-design-advances.mjs <advances.json>');
	process.exit(1);
}
const tables = JSON.parse(readFileSync(source, 'utf8').replace(/^﻿/u, ''));
const target = join(
	dirname(fileURLToPath(import.meta.url)),
	'..',
	'..',
	'text',
	'font-metrics',
	'design-advances-powerpoint.generated.ts',
);
const row = (values) =>
	values
		.trim()
		.split(/\s+/u)
		.map((value) => String(Math.round(Number(value) * 100) / 100))
		.join(' ');
const lines = [
	'/**',
	' * Unhinted glyph advances per 1000 em for printable ASCII (code points 32 to 126, in order),',
	' * regular and bold, measured through PowerPoint COM by',
	' * `scripts/pptx/record-pptx-design-advances.ps1` (BoundWidth of "H" + glyph + "H" at 100 pt).',
	' * For fonts Visio does not measure: Microsoft 365 cloud fonts and the fonts PowerPoint stands in',
	" * for with a look-alike, so a stand-in can be given the deck font's own widths.",
	' * GENERATED by `scripts/pptx/make-pptx-design-advances.mjs`: do not edit by hand.',
	' */',
	'export const POWERPOINT_DESIGN_ADVANCES: Readonly<',
	'\tRecord<string, { readonly regular: string; readonly bold: string }>',
	'> = {',
];
for (const font of Object.keys(tables).sort()) {
	const key = /^[a-z]+$/u.test(font) ? font : `'${font}'`;
	lines.push(`\t${key}: {`);
	lines.push(`\t\tregular:\n\t\t\t'${row(tables[font].regular)}',`);
	lines.push(`\t\tbold:\n\t\t\t'${row(tables[font].bold)}',`);
	lines.push('\t},');
}
lines.push('};');
writeFileSync(target, `${lines.join('\n')}\n`);
console.log('wrote', target);
