/**
 * Regression guard: OLE objects loaded from a `.pptx` must have their authored
 * preview image resolved into `previewImageData`: during load with
 * `eagerDecodeImages`, and otherwise by the host through the same lazy
 * picture resolution every binding runs (`collectImagePaths`), so a headless
 * load never converts an EMF preview it does not draw.
 *
 * The slide loader parses an OLE `<p:graphicFrame>` into a `type: 'ole'` element
 * and records the preview picture's relationship as a relative `previewImage`
 * path, but - until preview resolution was added to
 * {@link PptxHandlerRuntimeLoadSession.enrichOleElementsWithEmbeddedData} - never
 * turned that path into the `previewImageData` data-URL every binding's OLE
 * renderer actually reads. Without it, a real OLE object never showed its
 * preview and always fell back to the neutral type-badge placeholder (the same
 * class of gap the chart-enrichment-on-load guard covers for charts).
 *
 * The fixture is `e2e/fixtures/ole-embed.pptx` (one slide, one embedded PDF OLE
 * object with a real preview PNG), authored by
 * `e2e/fixtures/generate-ole-ink-fixtures.ts`.
 */
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, it, expect } from 'vitest';

import { PptxHandler } from '../../core/PptxHandler';
import type { PptxSlide } from '../../core/types';
import { applyImagePathPatches } from '../../editor/loader/element-patch-walker';
import { collectImagePaths } from '../../editor/loader/load-content-helpers';

const fixture = fileURLToPath(new URL('../fixtures/e2e/ole-embed.pptx', import.meta.url));

async function loadFixture(options?: { eagerDecodeImages: boolean }) {
	const bytes = readFileSync(fixture);
	const handler = new PptxHandler();
	const data = await handler.load(
		bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
		options,
	);
	return { handler, slides: data.slides };
}

function oleElements(slides: readonly PptxSlide[]) {
	const elements = slides.flatMap((s) => s.elements).filter((e) => e.type === 'ole');
	expect(elements.length).toBeGreaterThan(0);
	return elements.flatMap((e) => (e.type === 'ole' ? [e] : []));
}

/** The authored preview must be a URL the renderer can set as an <img src>. */
const PREVIEW_URL = /^(data:image\/|blob:)/u;

// The fixture is generated by the e2e global-setup and committed to the
// repo; skip defensively if a checkout lacks it rather than failing.
describe.skipIf(!existsSync(fixture))('ole enrichment on load', () => {
	it('decodes previewImageData during an eager load, with the embedded payload', async () => {
		const { slides } = await loadFixture({ eagerDecodeImages: true });
		for (const el of oleElements(slides)) {
			expect(el.previewImageData, `${el.id}: previewImageData`).toMatch(PREVIEW_URL);
			// The embedded payload is still recovered for download / open.
			expect(el.oleEmbeddedData, `${el.id}: oleEmbeddedData`).toMatch(/^data:/u);
		}
	});

	it('defers the preview by default and resolves it like a lazy picture', async () => {
		const { handler, slides } = await loadFixture();
		for (const el of oleElements(slides)) {
			expect(el.previewImageData, `${el.id}: previewImageData`).toBeUndefined();
			expect(el.previewImagePath, `${el.id}: previewImagePath`).toMatch(/^ppt\/media\//u);
			expect(el.oleEmbeddedData, `${el.id}: oleEmbeddedData`).toMatch(/^data:/u);
		}

		const { paths, refs } = collectImagePaths(slides);
		const resolved = new Map<string, string>();
		for (const path of paths) {
			const url = await handler.getImageData(path);
			if (url) resolved.set(path, url);
		}
		const patched = slides.map((s) => ({
			...s,
			elements: applyImagePathPatches(s.elements, resolved, refs),
		}));
		for (const el of oleElements(patched)) {
			expect(el.previewImageData, `${el.id}: previewImageData`).toMatch(PREVIEW_URL);
		}
	});
});
